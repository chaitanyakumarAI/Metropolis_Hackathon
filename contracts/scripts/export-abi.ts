// Writes the FirstFan ABI (and deployment info if present) into the web app.
import fs from "node:fs";
import path from "node:path";

const root = path.join(__dirname, "..");
const artifact = JSON.parse(
  fs.readFileSync(path.join(root, "artifacts", "contracts", "FirstFan.sol", "FirstFan.json"), "utf8"),
);
const out = path.join(root, "..", "web", "src", "lib", "abi.ts");
fs.writeFileSync(
  out,
  `// Generated by contracts/scripts/export-abi.ts — do not edit by hand.\nexport const firstFanAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
);
console.log(`Wrote ${out}`);
